// @desc    Generate alternative itinerary based on constraints
// @route   POST /api/itineraries/:id/alternatives
// @access  Private (requires JWT)
const generateAlternativeItineraryForTrip = async (req, res) => {
  try {
    const { id } = req.params;
    const { constraints } = req.body;

    if (!constraints) {
      return res.status(400).json({ 
        message: 'Constraints are required to generate alternative itinerary' 
      });
    }

    // Get the original itinerary
    const originalItinerary = await Itinerary.findOne({
      _id: id,
      userId: req.user._id
    });

    if (!originalItinerary) {
      return res.status(404).json({ 
        message: 'Itinerary not found or access denied' 
      });
    }

    // Generate alternative itinerary
    const alternativePlan = await generateAlternativeItinerary(
      originalItinerary.plan, 
      constraints
    );

    // Validate the alternative itinerary
    const validation = validateItinerary(alternativePlan);
    if (!validation.valid) {
      return res.status(500).json({ 
        message: 'Generated alternative itinerary is invalid',
        error: validation.error 
      });
    }

    // Create new itinerary document with alternative plan
    const alternativeItinerary = new Itinerary({
      tripId: originalItinerary.tripId,
      userId: req.user._id,
      plan: alternativePlan,
      constraintsUsed: {
        ...originalItinerary.constraintsUsed,
        ...constraints
      },
      generationMetadata: {
        aiProvider: 'gemini',
        modelUsed: 'gemini-1.5-flash',
        generationTime: 0,
        tokensUsed: 0,
        cacheHit: false
      },
      status: 'draft'
    });

    // Save the alternative itinerary
    await alternativeItinerary.save();

    res.status(201).json({
      success: true,
      message: 'Alternative itinerary generated successfully',
      data: {
        originalItineraryId: originalItinerary._id,
        alternativeItinerary: alternativeItinerary
      }
    });
  } catch (error) {
    console.error('Generate alternative itinerary error:', error);
    res.status(500).json({ 
      message: 'Failed to generate alternative itinerary',
      error: error.message 
    });
  }
};

