// @desc    Reset specific customization
// @route   DELETE /api/itineraries/:id/customizations/:modificationId
// @access  Private (requires JWT)
const resetCustomization = async (req, res) => {
  try {
    const { id, modificationId } = req.params;

    const itinerary = await Itinerary.findOne({
      _id: id,
      userId: req.user._id
    });

    if (!itinerary) {
      return res.status(404).json({ 
        message: 'Itinerary not found or access denied' 
      });
    }

    // Find the modification
    const modification = itinerary.customizations.modifiedActivities.id(modificationId);
    if (!modification) {
      return res.status(404).json({ 
        message: 'Modification not found' 
      });
    }

    // Find the day plan and reset the activity
    const dayPlan = itinerary.plan.dailyPlans.find(d => d.day === modification.day);
    if (dayPlan) {
      dayPlan[modification.timeSlot].activity = modification.originalActivity;
    }

    // Remove the modification
    itinerary.customizations.modifiedActivities.pull(modificationId);
    await itinerary.save();

    res.json({
      success: true,
      message: 'Customization reset successfully',
      data: {
        resetModification: modification
      }
    });
  } catch (error) {
    console.error('Reset customization error:', error);
    res.status(500).json({ 
      message: 'Failed to reset customization',
      error: error.message 
    });
  }
};

