// @desc    Generate AI itinerary for a trip
// @route   POST /api/itineraries/generate
// @access  Private (requires JWT)
const generateItineraryForTrip = async (req, res) => {
  try {
    const startTime = Date.now();
    const { tripId, preferences } = req.body;

    // Validate required fields
    if (!tripId) {
      return res.status(400).json({ 
        message: 'Trip ID is required' 
      });
    }

    // Get the trip and verify ownership
    const trip = await Trip.findOne({
      _id: tripId,
      userId: req.user._id
    });

    if (!trip) {
      return res.status(404).json({ 
        message: 'Trip not found or access denied' 
      });
    }

    // Check if trip has required dates
    if (!trip.startDate || !trip.endDate) {
      return res.status(400).json({ 
        message: 'Trip must have start and end dates to generate itinerary' 
      });
    }

    // Prepare inputs for AI service - Only basic trip info, no external API data
    const inputs = {
      destination: trip.destination,
      startDate: trip.startDate,
      endDate: trip.endDate,
      interests: preferences?.interests || ['exploration', 'culture', 'food'],
      budget: preferences?.budget || 'flexible',
      groupSize: preferences?.groupSize || 1,
      timeLimits: preferences?.timeLimits || null,
      weather: preferences?.weather || null,
      accessibility: preferences?.accessibility || null,
      forceRefresh: preferences?.forceRefresh === true
    };

    // Generate itinerary using AI - No external API data needed
    const generatedItinerary = await generateItinerary(inputs);

    // Validate the generated itinerary
    const validation = validateItinerary(generatedItinerary);
    if (!validation.valid) {
      return res.status(500).json({ 
        message: 'Generated itinerary is invalid',
        error: validation.error 
      });
    }

    // Calculate generation time
    const generationTime = Date.now() - startTime;

    // Create itinerary document
    const itinerary = new Itinerary({
      tripId: tripId,
      userId: req.user._id,
      plan: generatedItinerary,
      constraintsUsed: {
        budget: inputs.budget,
        timeLimits: inputs.timeLimits,
        weather: inputs.weather,
        accessibility: inputs.accessibility,
        groupSize: inputs.groupSize,
        interests: inputs.interests
      },
      generationMetadata: {
        aiProvider: 'gemini',
        modelUsed: 'gemini-1.5-flash',
        generationTime: generationTime,
        tokensUsed: 0, // Could be updated if API provides this info
        cacheHit: false,
        note: 'Itinerary structure generated by AI, external APIs handle transport/hotels/restaurants'
      }
    });

    // Save the itinerary
    await itinerary.save();

    res.status(201).json({
      success: true,
      message: 'Itinerary structure generated successfully',
      data: {
        itinerary: itinerary,
        generationTime: `${generationTime}ms`,
        trip: {
          id: trip._id,
          title: trip.title,
          destination: trip.destination,
          startDate: trip.startDate,
          endDate: trip.endDate
        },
        note: 'Transport, hotel, and restaurant options are available via separate API endpoints'
      }
    });
  } catch (error) {
    console.error('Generate itinerary error:', error);
    res.status(500).json({ 
      message: 'Failed to generate itinerary',
      error: error.message 
    });
  }
};

// @desc    Get all itineraries for a user
// @route   GET /api/itineraries
// @access  Private (requires JWT)
const getUserItineraries = async (req, res) => {
  try {
    const { tripId, status, limit = 10, page = 1 } = req.query;

    // Build query
    const query = { userId: req.user._id };
    if (tripId) query.tripId = tripId;
    if (status) query.status = status;

    // Execute query with pagination
    const itineraries = await Itinerary.find(query)
      .populate('tripId', 'title destination startDate endDate')
      .sort({ generatedAt: -1 })
      .limit(parseInt(limit))
      .skip((parseInt(page) - 1) * parseInt(limit));

    // Get total count for pagination
    const total = await Itinerary.countDocuments(query);

    res.json({
      success: true,
      data: itineraries,
      pagination: {
        currentPage: parseInt(page),
        totalPages: Math.ceil(total / parseInt(limit)),
        totalItems: total,
        itemsPerPage: parseInt(limit)
      }
    });
  } catch (error) {
    console.error('Get user itineraries error:', error);
    res.status(500).json({ 
      message: 'Failed to fetch itineraries',
      error: error.message 
    });
  }
};

