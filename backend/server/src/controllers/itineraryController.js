// @desc    Customize specific time slot in itinerary
// @route   PATCH /api/itineraries/:id/customize
// @access  Private (requires JWT)
const customizeItinerary = async (req, res) => {
  try {
    const { id } = req.params;
    const { day, timeSlot, customActivity, customLocation, customDuration, customCost, customNotes } = req.body;

    // Validate required fields
    if (!day || !timeSlot || !customActivity) {
      return res.status(400).json({ 
        message: 'Day, timeSlot, and customActivity are required' 
      });
    }

    // Validate timeSlot
    if (!['morning', 'afternoon', 'evening'].includes(timeSlot)) {
      return res.status(400).json({ 
        message: 'timeSlot must be morning, afternoon, or evening' 
      });
    }

    // Get the itinerary
    const itinerary = await Itinerary.findOne({
      _id: id,
      userId: req.user._id
    });

    if (!itinerary) {
      return res.status(404).json({ 
        message: 'Itinerary not found or access denied' 
      });
    }

    // Find the specific day
    const dayPlan = itinerary.plan.dailyPlans.find(d => d.day === parseInt(day));
    if (!dayPlan) {
      return res.status(404).json({ 
        message: `Day ${day} not found in itinerary` 
      });
    }

    // Store original activity in customizations
    const originalActivity = dayPlan[timeSlot];
    itinerary.customizations.modifiedActivities.push({
      day: parseInt(day),
      timeSlot: timeSlot,
      originalActivity: originalActivity.activity,
      newActivity: customActivity,
      modifiedAt: new Date()
    });

    // Update the activity with custom details
    dayPlan[timeSlot] = {
      activity: customActivity,
      location: customLocation || originalActivity.location,
      duration: customDuration || originalActivity.duration,
      cost: customCost || originalActivity.cost,
      notes: customNotes || originalActivity.notes
    };

    // Recalculate total day cost if cost was modified
    if (customCost) {
      const morningCost = parseFloat(dayPlan.morning.cost.replace('$', '')) || 0;
      const afternoonCost = parseFloat(dayPlan.afternoon.cost.replace('$', '')) || 0;
      const eveningCost = parseFloat(dayPlan.evening.cost.replace('$', '')) || 0;
      const totalDayCost = morningCost + afternoonCost + eveningCost;
      dayPlan.totalDayCost = `$${totalDayCost}`;
    }

    // Save the itinerary
    await itinerary.save();

    res.json({
      success: true,
      message: 'Itinerary customized successfully',
      data: {
        itinerary: itinerary,
        modification: {
          day: parseInt(day),
          timeSlot: timeSlot,
          originalActivity: originalActivity.activity,
          newActivity: customActivity,
          modifiedAt: new Date()
        }
      }
    });
  } catch (error) {
    console.error('Customize itinerary error:', error);
    res.status(500).json({ 
      message: 'Failed to customize itinerary',
      error: error.message 
    });
  }
};

